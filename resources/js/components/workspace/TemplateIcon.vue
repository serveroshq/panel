const brand = computed(() => brands[props.icon] ?? null);

const color = computed(() => {
    if (!props.colored || !brand.value) return undefined;

    const hex = brand.value.hex;
    const [r, g, b] = [0, 2, 4].map(
        (at) => parseInt(hex.slice(at, at + 2), 16) / 255,
    );
    const lightness = (Math.max(r, g, b) + Math.min(r, g, b)) / 2;

    return lightness < 0.2 || lightness > 0.85 ? undefined : `#${hex}`;
});
